"""Export editable family dictionaries as portable board YAML, JSON and SVG.

Run from any working directory. An optional --destination creates a copyable
handoff without changing the lab project. No network or research parsers needed.
"""

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import microcontroller_catalogue
import working_svg


def get_chips(**kwargs):
    return microcontroller_catalogue.get_chips(**kwargs)


def export(**kwargs):
    destination = Path(kwargs.get("destination", ROOT)).resolve()
    boards = microcontroller_catalogue.main()
    chips = get_chips()
    manifest = {
        "catalogue_schema": "oomp_microcontroller_reference_1",
        "research_date": "2026-10-22",
        "interface_defaults_version": 1,
        "interface_research_date": "2026-10-23",
        "coordinate_system": "PCB centre, mm, top view, +Y towards USB unless explicitly stated",
        "board_count": len(boards),
        "chip_count": len(chips),
        "boards": [],
        "chips": [],
        "legacy_id_aliases": {},
    }
    for option in boards + chips:
        identifier = microcontroller_catalogue.get_identifier(option=option)
        source_folder = ROOT / "source_file" / identifier
        target_folder = destination / "source_file" / identifier
        target_folder.mkdir(parents=True, exist_ok=True)
        for evidence in option["sources"]:
            local_file = evidence.get("local_file")
            if not local_file:
                continue
            source_path = (source_folder / local_file).resolve()
            target_path = (target_folder / local_file).resolve()
            if not source_path.is_relative_to(source_folder.resolve()) or not source_path.is_file():
                raise ValueError("Missing or external reference: " + str(source_path))
            if not target_path.is_relative_to(target_folder.resolve()):
                raise ValueError("Reference destination escapes item folder")
            if evidence.get("sha256") and hashlib.sha256(source_path.read_bytes()).hexdigest() != evidence["sha256"]:
                raise ValueError("Reference checksum mismatch: " + str(source_path))
            if source_path != target_path:
                target_path.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source_path, target_path)
        (target_folder / "definition.yaml").write_text(yaml.safe_dump(option, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
        if option["item_kind"] == "chip":
            manifest["chips"].append(identifier)
            continue
        (target_folder / "working_svg.svg").write_text(working_svg.microcontroller_svg(board=option), encoding="utf-8")
        entry = {
            "id": identifier,
            "name": option["name_readable"],
            "family": option["chip"]["family"],
            "definition": "source_file/" + identifier + "/definition.yaml",
            "svg": "source_file/" + identifier + "/working_svg.svg",
            "contact_records": len(option["pins"]),
            "located_contact_records": sum(pin["x_mm"] is not None for pin in option["pins"].values()),
            "exposed_gpio_count": len(option["gpio_summary"]["exposed"]),
            "located_mounting_holes": len(option["mounting_holes"]),
            "partial_or_related_holes": len(option["mounting_hole_candidates"]),
            "data_gaps": option["data_gaps"],
            "default_interface_status": {name: interface["status"] for name, interface in option["default_interfaces"].items()},
        }
        manifest["boards"].append(entry)
        for legacy in option.get("legacy_ids", []):
            manifest["legacy_id_aliases"][legacy] = identifier
    folder = destination / "catalogue" / "microcontrollers"
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "manifest.json").write_text(json.dumps(manifest, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
    (folder / "catalogue.json").write_text(json.dumps({"boards": boards, "chips": chips}, indent=4, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = []
    lines.append("# Microcontroller research coverage")
    lines.append("")
    lines.append("Research snapshot: 22 October 2026. Generated by `tools/export_microcontroller_catalogue.py` from the editable family dictionaries.")
    lines.append("")
    lines.append("Contact records count physical CAD pads (including separate castellations), connector contacts, or explicitly identified SDK aliases. They are not a count of independent GPIOs. An unlocated contact is listed beside its SVG and has no spatial hit target. Partial/related mounting holes never become SCAD mounting positions.")
    lines.append("")
    lines.append("| Board | Family | Contact records | Located | GPIOs | Located holes | Partial/related holes |")
    lines.append("| --- | --- | ---: | ---: | ---: | ---: | ---: |")
    for entry in manifest["boards"]:
        link = "../../" + entry["definition"]
        svg = "../../" + entry["svg"]
        lines.append(f"| [{entry['name']}]({link}) ([SVG]({svg})) | {entry['family']} | {entry['contact_records']} | {entry['located_contact_records']} | {entry['exposed_gpio_count']} | {entry['located_mounting_holes']} | {entry['partial_or_related_holes']} |")
    lines.append("")
    lines.append("## Outstanding evidence")
    lines.append("")
    for entry in manifest["boards"]:
        lines.append("### " + entry["name"])
        lines.append("")
        for gap in entry["data_gaps"]:
            lines.append("- " + gap)
        lines.append("")
    (folder / "coverage.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    lines = [
        "# Default interface coverage", "",
        "Interface research: 23 October 2026. Generated from the editable family dictionaries. See [the consumer contract](../../MICROCONTROLLERS.md#default-interface-data) before using these mappings.", "",
        "Values are GPIO numbers, not physical pad numbers. `?` means unverified; `none` means the framework defines no usable default. An asterisk means the GPIO has no matching contact in the catalogue. SDK-only aliases do not establish physical pad positions. Additional interfaces and all contact links are in each definition.", "",
        "| Board | Framework / variant | UART TX / RX | I2C SDA / SCL | SPI SCK / MOSI / MISO / SS | Additional defaults |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for board in boards:
        identifier = microcontroller_catalogue.get_identifier(option=board)
        defaults = board["default_interfaces"]

        def signal_text(interface, signal):
            if interface["status"] == "unverified":
                return "?"
            gpio = interface[signal + "_gpio"]
            suffix = "*" if interface["signal_status"][signal] == "not_in_pinout" else ""
            return "none" if gpio is None else str(gpio) + suffix

        cells = []
        for name, signals in (("uart", ("tx", "rx")), ("i2c", ("sda", "scl")), ("spi", ("sck", "mosi", "miso", "ss"))):
            interface = defaults[name]
            cells.append(" / ".join(signal_text(interface, signal) for signal in signals) + (" (" + interface["api"] + ")" if interface["api"] else ""))
        context = defaults["uart"]
        framework = (context["framework"] + " / " + context["variant"]) if context["framework"] else "unverified"
        extra = ", ".join(name + " (" + (interface["api"] or "aliases") + ")" for name, interface in defaults.items() if name not in ("uart", "i2c", "spi")) or "none recorded"
        link = "../../source_file/" + identifier + "/definition.yaml"
        lines.append(f"| [{board['name_readable']}]({link}) | {framework} | " + " | ".join(cells) + " | " + extra + " |")
    (folder / "interfaces.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Exported {len(boards)} boards and {len(chips)} chip references to {destination}")
    return manifest


def main(**kwargs):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, default=ROOT)
    arguments = parser.parse_args()
    return export(destination=arguments.destination)


if __name__ == "__main__":
    main()
